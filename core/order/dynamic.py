"""
core.order.dynamic
==================

A causal order generated by local light cones whose width depends on the
clock rate of the event (F6.3; the author's axiom 7 in its first form,
decisions of 22 Oct 2026).

Definitions
-----------
Fixed: the sprinkled events v with coordinates (t_v, x_v), sorted by t.
State of an event: its clock rate Pi_v in (0, 1] (set by the flux model;
Pi = 1 is the vacuum).

Local relation (the cone is set by the EARLIER event's clock; hypothesis
H1 of the theory, c_eff = c Pi^p, p = 2 from F7, a tested hypothesis):
    z R x   iff   t_x > t_z   and   |x_x - x_z| <= c_z (t_x - t_z),   c_z = Pi_z^p.
Order: the transitive closure of R, z < x iff a chain z R w1 R ... R x.
Acyclic: t increases strictly along every step of R, so no chain returns to
its start; the closure is a strict partial order.
Links: the Hasse diagram of the order, z -> x iff z < x and no w with
z < w < x. Every link is a pair of R (a longer chain would put an element
in between). With Pi = 1 everywhere R is the flat causal relation, already
transitive, and the links are the links of the sprinkling.
(When c varies R need not be transitive, so a pair z R x with no single w,
z R w R x, can still have a longer chain between: it is then NOT a link.
An earlier draft tested only single intermediates; it was replaced by the
exact construction below, which follows the definition through the
transitive closure, before any full run.)

Exact construction
------------------
Events are taken in increasing t. For x the candidates are its R-parents
z (z R x) with t_x - t_z <= window. The past of x is the union of the
pasts of its links; scanning the candidates by decreasing t and keeping a
bitset A of the past found so far, a candidate z is a link iff z is not in
A and precedes no other candidate already met (then A gains z and the past
of z). This is exact: a candidate below a non-link candidate y is below the
link above y, whose past is already in A. Pasts are stored as bit-packed
rows (N x N / 8 bytes).
The window bounds the length of a link in t: a link longer than the
window is not seen. In vacuum a link of a sprinkled region is limited by
the region (here the cylinder diameter); the validation compares two
windows and the flat links.
"""

from __future__ import annotations

from typing import Tuple

import numpy as np


def _cone_widths(Pi: np.ndarray, power: float) -> np.ndarray:
    c = np.asarray(Pi, float) ** float(power)
    if np.any(c <= 0.0) or np.any(c > 1.0):
        raise ValueError("cone widths must lie in (0, 1]")
    return c


def prec_local(A: np.ndarray, B: np.ndarray, cA: np.ndarray) -> np.ndarray:
    """Boolean (m x k): A_i R B_j (the local relation with A's cone width)."""
    dt = B[None, :, 0] - A[:, None, 0]
    cdt = cA[:, None] * dt
    t2 = cdt * cdt
    for d in range(1, A.shape[1]):
        dd = B[None, :, d] - A[:, None, d]
        t2 -= dd * dd
    return (dt > 0) & (t2 >= 0)


def order_links(X: np.ndarray, Pi: np.ndarray, power: float = 2.0, window: float = 1.5, *,
                rows: int = 32, block: int = 64, return_past: bool = False):
    """
    Links (CSR of parents, as core.order.links.links_csr) of the order generated by the local cones c = Pi^power
    on the time-sorted points X (module notes). Returns (ptr, idx), and the bit-packed pasts if return_past.
    """
    N, D = X.shape
    if np.any(np.diff(X[:, 0]) < 0):
        raise ValueError("X must be sorted by time")
    c = _cone_widths(Pi, power)
    t = X[:, 0]
    nb = (N + 7) // 8
    past = np.zeros((N, nb), dtype=np.uint8)
    bit = (np.uint8(1) << (np.arange(8, dtype=np.uint8)))      # bit of element e: past[:, e >> 3] & bit[e & 7]
    ptr = np.zeros(N + 1, dtype=np.int64)
    chunks = []
    total = 0
    for j0 in range(0, N, rows):
        j1 = min(N, j0 + rows)
        lo = int(np.searchsorted(t, t[j0] - window, side="left"))
        if j1 - lo <= 1:
            for j in range(j0, j1):
                ptr[j + 1] = total
            continue
        Rm = prec_local(X[lo:j1], X[j0:j1], c[lo:j1])           # (earlier points in the window) x (rows)
        for r, j in enumerate(range(j0, j1)):
            lo_j = int(np.searchsorted(t, t[j] - window, side="left"))
            cand = lo + np.nonzero(Rm[: j - lo, r])[0]
            cand = cand[cand >= lo_j]
            if cand.size == 0:
                ptr[j + 1] = total
                continue
            cand = cand[np.argsort(-t[cand], kind="stable")]     # decreasing time
            A = np.zeros(nb, dtype=np.uint8)
            keep = []
            for b0 in range(0, cand.size, block):
                cb = cand[b0:b0 + block]
                inA = (A[cb >> 3] & bit[cb & 7]) != 0
                # a precedes a later candidate b of the same block: bit a in past[b]
                P = past[np.ix_(cb, cb >> 3)] & bit[cb & 7][None, :]  # P[b, a] != 0 iff a < b
                below = (P != 0).any(axis=0)
                newk = cb[~inA & ~below]
                if newk.size:                                      # the links found in this block: A gains them and their pasts
                    A |= np.bitwise_or.reduce(past[newk], axis=0)
                    np.bitwise_or.at(A, newk >> 3, bit[newk & 7])
                    keep.append(newk)
            par = np.sort(np.concatenate(keep)) if keep else np.zeros(0, dtype=np.int64)
            past[j] = A
            chunks.append(par)
            total += par.size
            ptr[j + 1] = total
    idx = np.concatenate(chunks).astype(np.int64) if chunks else np.zeros(0, dtype=np.int64)
    return (ptr, idx, past) if return_past else (ptr, idx)


def order_links_bruteforce(X: np.ndarray, Pi: np.ndarray, power: float = 2.0) -> Tuple[np.ndarray, np.ndarray]:
    """Reference (small N): transitive closure of R by repeated composition, then its Hasse diagram."""
    N = len(X)
    c = _cone_widths(Pi, power)
    R = prec_local(X, X, c)
    T = R.copy()
    Ti = lambda M: M.astype(np.int32)                              # int32: a uint8 product would overflow past 255
    while True:                                                   # T <- T or T.T until nothing changes
        T2 = T | ((Ti(T) @ Ti(T)) > 0)
        if np.array_equal(T2, T):
            break
        T = T2
    between = (Ti(T) @ Ti(T)) > 0                                 # z < w < x for some w
    L = T & ~between
    ptr = np.zeros(N + 1, dtype=np.int64)
    out = []
    for j in range(N):
        par = np.nonzero(L[:, j])[0]
        out.append(par)
        ptr[j + 1] = ptr[j] + par.size
    idx = np.concatenate(out).astype(np.int64) if out else np.zeros(0, dtype=np.int64)
    return ptr, idx


def links_increase_time(X: np.ndarray, ptr: np.ndarray, idx: np.ndarray) -> bool:
    """Acyclicity check: every link goes forward in t (then no chain returns to its start)."""
    v = np.repeat(np.arange(len(ptr) - 1), np.diff(ptr))
    return bool(np.all(X[v, 0] > X[idx, 0]))


def link_set(ptr: np.ndarray, idx: np.ndarray) -> set:
    """The links as a set of (parent, child) pairs (for comparisons)."""
    return set(zip(idx.tolist(), np.repeat(np.arange(len(ptr) - 1), np.diff(ptr)).tolist()))
