"""
core.report
===========

python run.py report  ->  docs/test_list.md

One list of all tests, generated so that it never disagrees with the code:

  1. implemented tests: from the TEST headers in phases/ and the latest
     saved result of each part (replication and "older test version" marks);
  2. planned tests: docs/planned_tests.csv (edited by hand; a row
     disappears from this section as soon as a test file with that id exists);
  3. results of GTS Lab 2.x and 3.x: results/history_3x/overview.csv
     (the old designations and their results, assigned to the new ids).
"""

from __future__ import annotations

import csv
import time
from pathlib import Path
from typing import Dict, List

from . import registry, provenance
from .cli import status_line

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"


def _csv(path: Path) -> List[Dict[str, str]]:
    if not path.exists():
        return []
    with path.open(encoding="utf-8", newline="") as f:
        rd = csv.DictReader(f, delimiter=";")
        out = []
        for r in rd:
            r = dict(r)
            extra = r.pop(None, None)              # a ';' inside the last column (a note) splits it: join it back
            if extra and rd.fieldnames:
                last = rd.fieldnames[-1]
                r[last] = ";".join([r.get(last) or ""] + [x for x in extra if x is not None])
            out.append(r)
        return out


def _cell(s: str) -> str:
    return str(s).replace("|", "/").replace("\n", " ")


def write_report() -> Path:
    tests = registry.discover()
    names = {p[0]: p[2] for p in registry.PHASES}
    out = ["# Causality Lab: list of tests", "",
           f"Generated by `python run.py report` ({time.strftime('%Y-%m-%d %H:%M')}). Do not edit by hand: "
           "the test headers are in `phases/`, the plan in `docs/planned_tests.csv`, the history in "
           "`results/history_3x/overview.csv`.", "",
           "## Implemented tests", "",
           "| ID | Phase | Question tested | Level | Instruments | Depends on | Status (latest result) |",
           "| --- | --- | --- | --- | --- | --- | --- |"]
    for tid in sorted(tests, key=registry.sort_key):
        t = tests[tid]["test"]
        old = f" ({t['old_id']})" if t.get("old_id") else ""
        out.append(f"| {tid}{old} | {registry.phase_of(tid)} {names.get(registry.phase_of(tid), '')} | {_cell(t['question'])} | "
                   f"{t['level']} | {', '.join(t['meters']) or '—'} | {', '.join(t['depends_on']) or '—'} | "
                   f"{_cell(status_line(tid, tests[tid]))} |")
    plan = [r for r in _csv(DOCS / "planned_tests.csv") if r.get("ID") not in tests]
    out += ["", "## Planned tests", "",
            "| ID | Phase | Question tested | Level | Depends on | Note |", "| --- | --- | --- | --- | --- | --- |"]
    for r in sorted(plan, key=lambda r: registry.sort_key(r["ID"])):
        out.append(f"| {r['ID']} | {r['ID'].split('.')[0]} {names.get(r['ID'].split('.')[0], '')} | {_cell(r['Question'])} | "
                   f"{_cell(r['Level'])} | {_cell(r['Depends on'])} | {_cell(r['Note'])} |")
    hist = _csv(ROOT / "results" / "history_3x" / "overview.csv")
    out += ["", "## Results of GTS Lab 2.x and 3.x (history)", "",
            "The tests themselves are archived; their results survive. The saved 3.x records belong in `results/history_3x/`.", "",
            "| New ID | Original designation | Question tested | Result | Level |", "| --- | --- | --- | --- | --- |"]
    for r in sorted(hist, key=lambda r: registry.sort_key(r["New ID"])):
        out.append(f"| {r['New ID']} | {_cell(r['Original'])} | {_cell(r['Question'])} | {_cell(r['Result'])} | {_cell(r['Level'])} |")
    path = DOCS / "test_list.md"
    path.write_text("\n".join(out) + "\n", encoding="utf-8")
    return path
