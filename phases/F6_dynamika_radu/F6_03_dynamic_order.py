# ------------------------------------------------------------------------------------------------- geometry and drive

def geometry(p, seed):
    """One cylinder sprinkling (time-sorted), its flat links, radii and times."""
    S = sprinkle(Cylinder(int(p["D"]), 0.0, float(p["T"]), float(p["R"])), int(p["N"]), seed)
    ptr, idx = links_csr(S.X, S.rho, lam=float(p["lam"]))
    return S, ptr, idx, S.r(), S.X[:, 0]


def calibration_task(p, seed):
    """Uncapped offered flux at unit drive in the F3 analysis window (the capacity definition of the series)."""
    S, ptr, idx, r, t = geometry(p, seed)
    win = (t >= float(p["cal_t1"])) & (t < float(p["cal_t2"])) & (r < float(p["R_abs"]))
    return route_capacity(ptr, idx, np.full(S.n, float(p["s0"])), np.inf, r > float(p["R_abs"]))["offered"][win]


def drive(S, t, p, s_bg):
    """Background everywhere plus the ignition in the disk during the ignition window (F3.3g)."""
    a, b = (float(v) for v in p["ign_axes"])
    inside = (S.X[:, 1] / a) ** 2 + (S.X[:, 2] / b) ** 2 < 1.0
    on = (t >= float(p["t_ign1"])) & (t < float(p["t_ign2"]))
    return float(s_bg) + float(p["s_ign"]) * (inside & on)


def _nanmean(v):
    v = np.asarray(v, float)
    return float(v[np.isfinite(v)].mean()) if np.isfinite(v).any() else float("nan")


SER_KEYS = ("t", "N", "R_rms", "R_N", "B", "C_drop", "Q_drop", "pulse", "ring")


def slab_series(S, r, t, res, p):
    """Per slab: N_drop, R_rms, R_N, B, C_drop, Q_drop, pulse count, ring fraction (definitions of F3.3g)."""
    Rabs, ring = float(p["R_abs"]), float(p["ring"])
    edges = np.arange(float(p["t_obs1"]), float(p["t_obs2"]) + 1e-9, float(p["slab"]))
    sat = res["stored"] > 0
    out = {k: [] for k in SER_KEYS}
    for k in range(len(edges) - 1):
        m = (r < Rabs) & (t >= edges[k]) & (t < edges[k + 1])
        ms = m & sat
        nA = int(m.sum()) / (math.pi * Rabs ** 2)
        Nd = int(ms.sum())
        Rrms = float(np.sqrt(2.0 * np.mean(r[ms] ** 2))) if Nd else float("nan")
        RN = float(np.sqrt(Nd / (math.pi * nA))) if nA > 0 else float("nan")
        inside = m & (r < Rrms) if Nd else np.zeros_like(m)
        ringm = m & (r >= ring)
        out["t"].append(0.5 * (edges[k] + edges[k + 1]))
        out["N"].append(Nd)
        out["R_rms"].append(Rrms)
        out["R_N"].append(RN)
        out["B"].append(RN / Rrms if Nd and Rrms > 0 else float("nan"))
        out["C_drop"].append(float(sat[inside].mean()) if inside.any() else float("nan"))
        out["Q_drop"].append(float(res["stored"][ms].sum()))
        out["pulse"].append(int((res["P"][m] > 0).sum()))
        out["ring"].append(float(sat[ringm].mean()) if ringm.any() else float("nan"))
    return out


def average_series(series_list):
    """Element-wise mean over iterations (nan-aware): the observables of the self-consistent ensemble."""
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        return {k: list(np.nanmean(np.array([s[k] for s in series_list], float), axis=0)) for k in SER_KEYS}


def window_stats(ser, p):
    """Early / late means: N, R_rms, C_drop, ring; died flag; growth (F3.3h)."""
    t = np.asarray(ser["t"])
    e = (t >= p["early"][0]) & (t < p["early"][1])
    l_ = (t >= p["late"][0]) & (t < p["late"][1])
    N = np.asarray(ser["N"], float)
    R = np.asarray(ser["R_rms"], float)
    Ne, Nl = float(N[e].mean()), float(N[l_].mean())
    Re, Rl = _nanmean(R[e]), _nanmean(R[l_])
    died = (Ne == 0.0) or (Nl < float(p["die_frac"]) * Ne)
    if died:
        Rl = float("nan")
    C_late = _nanmean(np.asarray(ser["C_drop"], float)[l_]) if not died else float("nan")
    return {"N_early": Ne, "N_late": Nl, "R_early": Re, "R_late": Rl, "died": bool(died), "C_late": C_late,
            "growth": (Rl - Re) if not died else float("nan"),
            "ring_late": _nanmean(np.asarray(ser["ring"], float)[l_])}


# ------------------------------------------------------------------------------------------------- the dynamic order

def route(ptr, idx, s, C, ab, p, pulse=True, Pi_sat=None, order=None):
    """F3.3g flux on given links: bistable (pulse + threshold + capacity channel) or control (no pulse)."""
    if not pulse:
        return route_pulse(ptr, idx, s, C, ab, "none", float(p["omega"]), order=order)
    ps = float(p["Pi_sat"]) if Pi_sat is None else float(Pi_sat)
    return route_pulse(ptr, idx, s, C, ab, str(p["rule"]), float(p["omega"]), order=order, dq_crit=float(p["dq_crit"]),
                       channel="capacity", Pi_sat=ps, m=float(p["m"]))


def solve_dynamic(S, r, t, s, C, ab, p, Pi_sat=None, n_burn=None, n_avg=None, window=None):
    """
    Self-consistent order and flux (module notes): iterate from the vacuum; return the series of the averaging
    iterations, the last Pi and links, and the instrument data (balance, acyclicity, flip fraction per iteration).
    """
    n_burn = int(p["burn_in"]) if n_burn is None else n_burn
    n_avg = int(p["n_avg"]) if n_avg is None else n_avg
    window = float(p["window"]) if window is None else window
    d = float(p["damp"])
    Pi = np.ones(S.n)
    series, flips, bal, acyc, iters = [], [], 0.0, True, 0
    ptr = idx = res = None
    Pi_links = Pi
    for it in range(n_burn + n_avg):
        Pi_links = Pi.copy()                            # the clocks the current links are built from
        ptr, idx = order_links(S.X, Pi_links, float(p["power"]), window)
        acyc &= links_increase_time(S.X, ptr, idx)
        res = route(ptr, idx, s, C, ab, p, Pi_sat=Pi_sat)
        bal = max(bal, pulse_balance(res))
        iters = it + 1
        change = np.abs(res["Pi"] - Pi)
        flips.append(float((change > 0.01).mean()))
        if it >= n_burn:
            series.append(slab_series(S, r, t, res, p))
        if float(change.max()) == 0.0:                 # an exact fixed point (e.g. Pi_sat = 1): nothing more to do
            if not series:
                series.append(slab_series(S, r, t, res, p))
            break
        Pi = (1.0 - d) * Pi + d * res["Pi"]
    return {"series": series, "Pi": Pi, "Pi_links": Pi_links, "ptr": ptr, "idx": idx, "res": res, "balance": bal, "acyclic": acyc,
            "flips": flips, "iterations": iters}


